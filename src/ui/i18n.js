const DICT = { en: EN, zh: ZH };

let current = 'en';
try {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored && DICT[stored]) current = stored;
} catch (e) { /* storage may be blocked */ }

export function getLang() { return current; }
export function isZh() { return current === 'zh'; }

export function setLang(id) {
  if (!DICT[id] || id === current) return false;
  current = id;
  try { localStorage.setItem(STORAGE_KEY, id); } catch (e) { /* ignore */ }
  return true;
}

/** Translate a UI key, with `{name}` placeholder substitution. */
export function t(key, vars) {
  const table = DICT[current] || EN;
  let s = table[key];
  if (s === undefined) s = EN[key];
  if (s === undefined) s = key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  }
  return s;
}
